// @ts-check
/**
 * The clip registry: which recorded clip (assets/audio/<lang>/<id>.wav)
 * speaks which label. Pure functions, used by record-server.mjs and tests.
 *
 * Clips are keyed by label text, so items in different sets with the same
 * word (ვაშლი in Mixed and Fruit) share one recording. A clip file is named
 * after the first item (in itemSets order) that has that label.
 */

import { itemSets, labelFor } from '../js/items.js';

export const CLIPS_BEGIN = '  // clips:begin (generated by scripts/record-server.mjs)';
export const CLIPS_END = '  // clips:end';

/** @typedef {Record<string, Record<string, string>>} Registry  lang -> label -> path */

/**
 * The words to record in `lang`: one per distinct label, in itemSets order.
 * @param {string} lang
 * @returns {{ id: string, label: string, image: string }[]}
 */
export function wordsFor(lang) {
  /** @type {Map<string, { id: string, label: string, image: string }>} */
  const byLabel = new Map();
  for (const item of Object.values(itemSets).flat()) {
    const label = labelFor(item, lang);
    if (!byLabel.has(label)) byLabel.set(label, { id: item.id, label, image: item.image });
  }
  return [...byLabel.values()];
}

/** Path of the clip for the word with `id` in `lang`. */
export function clipPath(lang, id) {
  return `assets/audio/${lang}/${id}.wav`;
}

/**
 * Build the registry from the clip files that exist.
 * @param {Record<string, string[]>} files  lang -> ids of existing .wav files
 * @returns {Registry}
 */
export function buildRegistry(files) {
  /** @type {Registry} */
  const registry = {};
  for (const [lang, ids] of Object.entries(files)) {
    const have = new Set(ids);
    const entries = wordsFor(lang)
      .filter((w) => have.has(w.id))
      .map((w) => [w.label, clipPath(lang, w.id)]);
    if (entries.length) registry[lang] = Object.fromEntries(entries);
  }
  return registry;
}

/**
 * Source of js/clips.js for a registry.
 * @param {Registry} registry
 */
export function renderClipsModule(registry) {
  const body = Object.entries(registry)
    .map(([lang, byLabel]) => {
      const lines = Object.entries(byLabel).map(([label, path]) => `    ${JSON.stringify(label)}: ${JSON.stringify(path)},`);
      return `  ${lang}: {\n${lines.join('\n')}\n  },`;
    })
    .join('\n');
  return [
    '// Generated by scripts/record-server.mjs from assets/audio/<lang>/. Do not edit.',
    '/** Recorded clips: language -> label text -> file. @type {Record<string, Record<string, string>>} */',
    body ? `export const clips = {\n${body}\n};` : 'export const clips = {};',
    '',
  ].join('\n');
}

/**
 * sw.js with the clips block replaced by the registry's files.
 * @param {string} source  current sw.js
 * @param {Registry} registry
 */
export function updateServiceWorker(source, registry) {
  const begin = source.indexOf(CLIPS_BEGIN);
  const end = source.indexOf(CLIPS_END);
  if (begin < 0 || end < 0 || end < begin) throw new Error('sw.js has no clips block');
  const paths = Object.values(registry).flatMap((byLabel) => Object.values(byLabel));
  const block = [CLIPS_BEGIN, ...paths.map((p) => `  '${p}',`), ''].join('\n');
  return source.slice(0, begin) + block + source.slice(end);
}
