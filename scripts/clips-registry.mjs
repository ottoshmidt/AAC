/**
 * The clip registry: which recorded clip (assets/audio/<lang>/<voice>/<id>.wav)
 * speaks which label in which voice. Pure functions, used by
 * record-server.mjs and tests.
 *
 * Clips are keyed by label text, so items in different sets with the same
 * word (ვაშლი in Mixed and Fruit) share one recording. A clip file is named
 * after the first item (in itemSets order) that has that label. Letters of
 * the language's own alphabet (js/letters.js) are recorded the same way.
 */

import { itemSets, labelFor } from '../js/items.js';
import { letterSets } from '../js/letters.js';

export const CLIPS_BEGIN = '  // clips:begin (generated by scripts/record-server.mjs)';
export const CLIPS_END = '  // clips:end';

/** @typedef {Record<string, Record<string, Record<string, string>>>} Registry  lang -> voice -> label -> path */

/**
 * The words to record in `lang`: one per distinct label, in itemSets order.
 * @param {string} lang
 * @returns {{ id: string, label: string, image: string }[]}
 */
export function wordsFor(lang) {
  /** @type {Map<string, { id: string, label: string, image: string, text?: string }>} */
  const byLabel = new Map();
  // The pictures first, then the letters of that language's own alphabet.
  for (const item of [...Object.values(itemSets).flat(), ...(letterSets[lang] ?? [])]) {
    const label = labelFor(item, lang);
    if (!byLabel.has(label)) byLabel.set(label, { id: item.id, label, image: item.image ?? '', text: item.text });
  }
  return [...byLabel.values()];
}

/** Path of the clip for the word with `id` in `lang`, spoken by `voice`. */
export function clipPath(lang, voice, id) {
  return `assets/audio/${lang}/${voice}/${id}.wav`;
}

/**
 * Build the registry from the clip files that exist.
 * @param {Record<string, Record<string, string[]>>} files  lang -> voice -> ids of existing .wav files
 * @returns {Registry}
 */
export function buildRegistry(files) {
  /** @type {Registry} */
  const registry = {};
  for (const [lang, voices] of Object.entries(files)) {
    const words = wordsFor(lang);
    for (const [voice, ids] of Object.entries(voices)) {
      const have = new Set(ids);
      const entries = words.filter((w) => have.has(w.id)).map((w) => [w.label, clipPath(lang, voice, w.id)]);
      if (entries.length) (registry[lang] ??= {})[voice] = Object.fromEntries(entries);
    }
  }
  return registry;
}

/**
 * Source of js/clips.js for a registry.
 * @param {Registry} registry
 */
export function renderClipsModule(registry) {
  const body = Object.entries(registry)
    .map(([lang, voices]) => {
      const voiceBlocks = Object.entries(voices).map(([voice, byLabel]) => {
        const lines = Object.entries(byLabel).map(([label, path]) => `      ${JSON.stringify(label)}: ${JSON.stringify(path)},`);
        return `    ${voice}: {\n${lines.join('\n')}\n    },`;
      });
      return `  ${lang}: {\n${voiceBlocks.join('\n')}\n  },`;
    })
    .join('\n');
  return [
    '// Generated by scripts/record-server.mjs from assets/audio/<lang>/<voice>/. Do not edit.',
    '/** Recorded clips: language -> voice -> label text -> file. @type {Record<string, Record<string, Record<string, string>>>} */',
    body ? `export const clips = {\n${body}\n};` : 'export const clips = {};',
    '',
  ].join('\n');
}

/**
 * sw.js with the clips block replaced by the registry's files.
 * @param {string} source  current sw.js
 * @param {Registry} registry
 */
export function updateServiceWorker(source, registry) {
  const begin = source.indexOf(CLIPS_BEGIN);
  const end = source.indexOf(CLIPS_END);
  if (begin < 0 || end < 0 || end < begin) throw new Error('sw.js has no clips block');
  const paths = Object.values(registry).flatMap((voices) => Object.values(voices).flatMap((byLabel) => Object.values(byLabel)));
  const block = [CLIPS_BEGIN, ...paths.map((p) => `  '${p}',`), ''].join('\n');
  return source.slice(0, begin) + block + source.slice(end);
}
